def role_description(role: str) -> str | None:
    """역할의 표준 설명을 반환합니다.

    Args:
        role: ROLES의 키.

    Returns:
        표준 설명. 분류표 밖의 역할(ROLE_OTHER 포함)이면 None.
    """
    entry = ROLES.get(role)
    return entry.description if entry else None
